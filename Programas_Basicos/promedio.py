#calcular el promedio de tres numeros ingresados por el usuario
print("Ingrese los tres números que desea promediar")
n1=float(input("Primer número: "))
n2=float(input("Segundo número: "))
n3=float(input("Tercer número: "))
promedio=(n1+n2+n3)/3
print("El promedio de los números que ingresó es ", promedio)